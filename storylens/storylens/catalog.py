"""CATALOG.md: one readable page with everything in the workspace, so Claude (and you) know what exists.

Regenerated after every job and by the watcher. It is a summary only: the facts live in library/<title>/understanding.
"""
from __future__ import annotations
from collections import Counter
from pathlib import Path
from .util import read_json, write_text


def build(ws) -> str:
    from . import understand, views, library
    from .jobs import list_jobs
    from .tasks import list_tasks
    from .workspace import profile
    L = ["# Catalog of this storylens workspace", "",
         "Generated by storylens. To act on any of this, write a request into `requests/new/` (see CLAUDE.md).", ""]
    titles = ws.titles()
    L.append(f"## Titles ({len(titles)})\n")
    if not titles: L.append("None yet. Add one with a request `{\"do\": \"add_title\", ...}`.\n")
    for t in titles:
        prof = profile(t)
        L.append(f"### {t['name']}  — id `{t['id']}`\n")
        L.append(f"- kind: {t['kind']} ({prof}); media: {len(t['media'])}; cast given: {', '.join(t.get('cast', [])) or '-'}")
        eps = [f"{m['id']}" + (f" S{m['season']:02d}E{m['episode']:02d}" if m.get("season") else "") + ("" if m.get("subs") else " (no subtitles!)")
               for m in t["media"][:40]]
        if eps: L.append(f"- media: {', '.join(eps)}" + (" …" if len(t["media"]) > 40 else ""))
        if not ws.current_version(t["id"]):
            L.append("- understanding: **not built yet** → request `{\"do\": \"understand\", \"title\": \"" + t["id"] + "\"}`\n"); continue
        U = understand.load(ws, t["id"]); b = U["bible"]
        L.append(f"- understanding: {U['version']} — {len(U['beats'])} beats, {len(U['facts'])} facts"
                 f" (`library/{t['id']}/understanding/{U['version']}/`)")
        if b.get("logline"): L.append(f"- logline: {b['logline']}")
        chars = sorted(U["characters"], key=lambda c: -c.get("importance", 0))[:14]
        if chars: L.append(f"- {'speakers' if prof == 'discourse' else 'characters'}: "
                           + "; ".join(f"{c['name']}" + (f" ({c.get('role')})" if c.get("role") else "") for c in chars))
        ths = sorted(b.get("threads", []), key=lambda x: -x.get("importance", 0))[:10]
        if ths: L.append("- threads: " + "; ".join(f"`{x['id']}` {x['title']}" for x in ths))
        if b.get("themes"): L.append("- themes: " + ", ".join(b["themes"][:12]))
        tops = Counter(tp.lower() for f in U["facts"] for tp in f.get("topics") or [])
        if tops: L.append("- top topics: " + ", ".join(f"{k} ({n})" for k, n in tops.most_common(20)))
        vs = views.list_views(ws, t["id"])
        if vs: L.append("- lenses built: " + "; ".join(f"`{v['id']}` {v['title']} ({v['items']} items)" for v in vs[:20]))
        L.append("")
    cols = library.collections(ws)
    L.append(f"## Collections ({len(cols)})\n")
    for c in cols:
        ls = library.list_lenses(ws, c["id"])
        L.append(f"- `{c['id']}` {c['name']}: {', '.join(c['titles'])}" + (f" — lenses: {', '.join(x['id'] for x in ls[:10])}" if ls else ""))
    L.append("")
    jobs = list_jobs(ws)[:25]
    L.append("## Recent jobs\n")
    if not jobs: L.append("None yet.")
    for j in jobs:
        st = j["state"]; arts = sorted(p.name for p in (Path(ws.jobs) / j["id"] / "artifacts").glob("*") if p.is_file())
        L.append(f"- `{j['id']}` {j['kind']} {j['title']} — **{st.get('status', '')}** {st.get('stage', '')}"
                 + (f" — artifacts: {', '.join(arts[:8])}" if arts else "") + (f" — {st.get('message')}" if st.get("status") == "failed" else ""))
    L.append("")
    open_ = list_tasks(ws, "open")
    L.append(f"## Claude tasks\n\n{len(open_)} open — see `tasks/QUEUE.md`.\n")
    return "\n".join(L)


def write(ws):
    try:
        write_text(Path(ws.root) / "CATALOG.md", build(ws))
    except Exception as e:  # never let the catalog break a job
        write_text(Path(ws.root) / "CATALOG.md", f"# Catalog\n\n(could not be generated: {type(e).__name__}: {e})\n")
