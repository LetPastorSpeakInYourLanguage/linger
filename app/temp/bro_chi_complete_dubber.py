def create_speaker_segments(speech_dict, source_file='source.wav'):
    with wave.open(source_file, 'rb') as source:
        sample_rate = source.getframerate()
        sample_width = source.getsampwidth()
        n_channels = source.getnchannels()
        speaker_segments = {}
        for segment in speech_dict['segments']:
            speaker_id = segment['speaker']
            start_time = segment['start']
            end_time = segment['end']
            start_frame = int(start_time * sample_rate)
            end_frame = int(end_time * sample_rate)
            n_frames = end_frame - start_frame
            source.rewind()
            source.setpos(start_frame)
            segment_data = source.readframes(n_frames)
            segment_array = np.frombuffer(segment_data, dtype=np.int16)
            if speaker_id not in speaker_segments:
                speaker_segments[speaker_id] = []
            speaker_segments[speaker_id].append(segment_array)
    return speaker_segments,sample_rate,sample_width

