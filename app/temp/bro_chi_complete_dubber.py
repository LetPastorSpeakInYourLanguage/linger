def load_embeddings(fpath):
    """
    Load a dictionary of embeddings from a file.

    :param fpath: path to load the file from
    :return: dictionary of label to embedding
    """
    data = np.load(fpath)
    return {key: data[key] for key in data.files}

def compare_embedding(embedding, mean_embeddings):
    """
    Compare an embedding to a dictionary of mean embeddings and return confidence scores.

    :param embedding: embedding to compare
    :param mean_embeddings: dictionary of label to mean embedding
    :return: dictionary of label to confidence score
    """
    scores = {}

    for label, mean_embedding in mean_embeddings.items():
        # Calculate the cosine similarity between the embedding and the mean embedding
        similarity = np.dot(embedding, mean_embedding) / (np.linalg.norm(embedding) * np.linalg.norm(mean_embedding))

        # Store the similarity as the confidence score for the label
        scores[label] = similarity

    return scores

