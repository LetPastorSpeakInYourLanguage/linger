import numpy as np

def get_closest_utterances(utterances_dict,sample_rate= 32000):
    # Initialize VoiceEncoder
    encoder = VoiceEncoder()

    # Initialize output dictionary
    output_dict = {}

    # Loop over speakers
    for speaker_id, utterances in utterances_dict.items():
        # Calculate embeddings for each utterance
        embeddings = np.array([encoder.embed_utterance(preprocess_wav(utt)) for utt in utterances])

        # Calculate mean embedding
        mean_embedding = np.mean(embeddings, axis=0)

        # Calculate distances from mean embedding
        distances = np.linalg.norm(embeddings - mean_embedding, axis=1)

        # Sort utterances by distance from mean embedding
        sorted_indices = np.argsort(distances)
        sorted_utterances = [utterances[i] for i in sorted_indices]

        # Add closest utterances to list until total duration exceeds 30 seconds
        selected_utterances = []
        total_duration = 0
        for utt in sorted_utterances:
            selected_utterances.append(utt)
            total_duration += len(utt) / sample_rate
            if total_duration > 30:
                selected_utterances.pop()
                break

        # Recalculate mean embedding using selected utterances
        selected_embeddings = np.array([encoder.embed_utterance(preprocess_wav(utt)) for utt in selected_utterances])
        mean_embedding = np.mean(selected_embeddings, axis=0)

        # Add results to output dictionary
        output_dict[speaker_id] = {
            'selected_utterances': selected_utterances,
            'mean_embedding': mean_embedding
        }

    return output_dict

