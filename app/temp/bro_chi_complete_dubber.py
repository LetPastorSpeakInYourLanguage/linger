def concatenate_subtitles_and_audio(starts:list[str], outfile:str='output'):
    """
    starts: 'filename' is a dictioanry of start times
    and the value pointed to by this key is a filename where filename.mp3 is audio
    and filename.vtt is the subtitle for the respective subtitle
    """

    #check preconditions
    assert len(audio_files) == len(subtitle_files), "The number of audio files and subtitle files must be the same"

    # Concatenate audio files && subtitle files from empty
    combined_audio = np.array([])
    combined_subtitles = webvtt.WebVTT()

    for start in starts:
        audio, sr = librosa.load(f'{start}.mp3', sr=None, mono=False)
        combined_audio = np.concatenate((combined_audio, audio))

        subtitles = webvtt.read(f'{start}.vtt')
        for i, caption in enumerate(subtitles):
            start = datetime.strptime(caption.start, '%H:%M:%S.%f') + timedelta(seconds=float(start))
            end = datetime.strptime(caption.end, '%H:%M:%S.%f') + timedelta(seconds=float(start))
            text = caption.text
            combined_subtitles.captions.append(webvtt.Caption(
                start=start.strftime('%H:%M:%S.%f'),
                end=end.strftime('%H:%M:%S.%f'),
                text=text
            ))

    # Save concatenated audio and subtitle file
    sf.write(f"{outfile}.mp3", combined_audio, sr)
    combined_subtitles.save(f"{outfile}.vtt")

    return outfile


