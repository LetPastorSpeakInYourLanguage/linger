async def _edgeTTS_batch(subtitle:dict,output:str) -> None:
    """for Every Speaker We Will Generate
        segments content:
            speakers {speaker => edgeTTS_voice} #mapping Dictionary
            segments [text,start,end,speaker,speechOptions]
            speechOptions [pitch,volume,rate] | None for non-manupilated!
    Args:
        segments (dict): the data of subtitles
        output (str): the folder to save extractions
    """
    # Make Sure the Output folder is Available and Clean
    shutil.rmtree(output)
    os.makedirs(output) #,exist_ok=True There should be error if exists
    speaker_map = subtitle['speakers']
    communicate = Communicate("ጀምር...", 'am-ET-MekdesNeural') #Just to initiate

    # Gen the entire sub with the timing of the source once, no need to do every
    subtitle_extract = {}
    for idx,segment in enumerate(subtitle['segments']):
        # Set the current Item Data
        communicate.text = segment['trans'] #mark the translated text as src for tts
        communicate.voice = speaker_map[segment['speaker']] #This Returns EdgeTTS voice to USE

        # Set The voice Variation Options
        if segment['speechOptions']:
            communicate.pitch, \
            communicate.volume, \
            communicate.rate = segment['speechOptions']
        else : # Reset any previous Changes !!! if none applied to current
            communicate.pitch, \
            communicate.volume, \
            communicate.rate = '+0Hz','+0%','+0%'

        # * Incase We have multiple strips in a single genete
        sub_data = []
        with open(f'{output}/{idx}.mp3', "wb") as file:
            async for chunk in communicate.stream():
                if chunk["type"] == "audio":
                    file.write(chunk["data"])
                elif chunk["type"] == "WordBoundary":
                    sub_data.append(((chunk['offset'], chunk["duration"]), chunk["text"]))

        subltitle_extract[idx] = sub_data
        # Generate also for SRC_LANG
        subMaker_TR_VTT(subtitle=subtitle,subtitle_extract=subtitle_extract,output=output)


def edgeTTS_generate(subtitles:dict,output:str=SEGMENTS_PATH)->None:
    """generates speech and subtitles using edgeTTS and saves to output

    Args:
        subtitles (dict): the segments data from proofReading
        output (str, optional): the folder to store generations. Defaults to SEGMENTS_PATH.
    """
    loop = asyncio.get_event_loop_policy().get_event_loop()
    try:
        loop.run_until_complete(_edgeTTS_batch(subtitle=subtitles,output=SEGMENTS_PATH))
    finally:
        loop.close()

