def compile_single_audio(
                segments:dict,
                audio_dir=SEGMENTS_PATH,
                bg_audio='split/source/background.mp3',
                output_file='TR_AUDIO.mp3'):
    # Initialize an empty audio segment
    main_audio = AudioSegment.silent(duration=0)
    # Load the background audio
    background_audio = AudioSegment.from_mp3(bg_audio)

    # Initialize an empty audio segment for the segments
    segments_audio = AudioSegment.silent(duration=len(background_audio))

    # Add each segment to the segments audio at its start time
    for i, segment in enumerate(segments):
        start = segment['start']
        # Load the segment file
        segment_audio = AudioSegment.from_mp3(f'{i}.mp3')

        # Calculate the start time in milliseconds
        start_time_ms = int(start_time * 1000)

        # Overlay the segment audio onto the segments audio at the start time
        segments_audio = segments_audio.overlay(segment_audio, position=start_time_ms)

    # Overlay the segments audio onto the background audio
    main_audio = background_audio.overlay(segments_audio)

    # Save the result
    main_audio.export(output_file, format="mp3")

