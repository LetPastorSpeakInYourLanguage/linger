def place_multi_subs(segment_duration, sub_data):
    """
    takes the length on which to place a set of centerpoints evenly
    """
    # Calculate the distance between each item
    distance = segment_duration / (len(sub_data) + 1)
    # Create a dictionary to store each item and its position
    positions = {}
    # Place each item at the correct position
    for i, _ in enumerate(sub_data):
        positions[i] = (i + 1) * distance
    return positions

