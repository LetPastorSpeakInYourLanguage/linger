def extract_time_and_text(s):
    # Regular expression pattern for time and text
    time_pattern = r'<(\d{2}:\d{2}:\d{2}\.\d{3})>'
    text_pattern = r'<c>(.*?)</c>'

    # Find all times and texts in the string
    times = re.findall(time_pattern, s) # word level start timestamps for the word sequences
    texts = re.findall(text_pattern, s) # all words in the c tag :all except the first one

    # The first text is not enclosed in <c> tags, so we need to handle it separately
    first_text = s.split('<', 1)[0].strip()

    # Combine the first text with the other texts
    texts = [first_text] + texts
    text = "".join(texts) #the text for the total segment

    formated_time = [time_to_float(time) for time in times]
    # returns the texts and times as tuple
    # this returns segment text and start time for each following word
    return text,formated_time

def time_to_float(time_string):
    h, m, s = map(float, time_string.split(':'))

    # clean rounding using string formatting
    return float("%.3f" % (h * 3600 + m * 60 + s))

