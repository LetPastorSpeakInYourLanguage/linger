def batch_translate(segments, src_lang="en", tr_lang="am"):
    batched_segments = []
    current_segment = ''
    rem_items = []
    for segment in segments:
        # skip over empty lines and prepare for poping
        if segment['text'] == '':
            rem_items.append(segment)
            continue
        # 4k words + 1k words from prev as context maintainance window
        if len(current_segment) + len(segment['text']) <= 5000:
            current_segment += segment['text'] + '\n'
        else:
            batched_segments.append(current_segment.strip())
            current_segment = segment['text'] + '\n'
    if current_segment:
        batched_segments.append(current_segment.strip())

    # remove empty lines
    for trash in rem_items:
        segments.remove(trash)

    translated_results = []
    for batch in batched_segments:
        # Translate the batch but ignore the first 1000 characters (the context window)
        translation = translate(batch, tr_lang, src_lang)

        # because word count accross languages are not the same: we go with segment count
        translated_results.extend(translation.split("\n"))
    try:
        assert len(translated_results) == len(segments)
        #push translation into the same dictionary
        for idx in range(len(segments)):
            segments[idx]['trans'] = translated_results[idx]
    except:
        print("something is wrong",len(translated_results),len(segments))
    return segments

