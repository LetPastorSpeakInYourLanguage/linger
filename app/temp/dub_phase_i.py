def vtt_json(caption_lang='en')->tuple[dict,str]:
    """Generates Json from .vtt caption of a youtube video for a given language

    Args:
        caption_lang (str, optional): the language of the video. Defaults to 'en'.

    Raises:
        Exception: If a subtitle for the Given language is not found it raises Error

    Returns:
        tuple[dict,str]: The generated Json Segments and the Filepath of the Caption
    """
    expected_file = f'captions.{caption_lang}.vtt'
    if not os.path.isfile(expected_file):
        # Get the current directory
        current_directory = os.getcwd()
        expected_file = glob.glob(os.path.join(current_directory, f'*{caption_lang}*.vtt'))[0]
        if not expected_file:
            raise Exception("Subtitles not possible for this Video!")
    segments = parse_vtt(open(expected_file, 'r').read())
    return segments, expected_file

