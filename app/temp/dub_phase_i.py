def ipython_play_audio(audio_path:str,start:float|None,end:float|None):
    """display segment or full audio from file

    Args:
        audio_path (str): local path of the audio file
        start (float, optional): if Provided its the second of crop start
        end (float, optional): deterimines crop end. Defaults to total length.
    """
    # Load the audio file
    sample_rate, data = wavfile.read(audio_path)

    # Convert the times to sample indices
    start_sample = int(start * sample_rate) if start else 0
    end_sample = int(end * sample_rate) if end else len(data) -1

    # Extract the segment
    segment = data[start_sample:end_sample]

    # Create an Audio object and display it
    display(Audio(segment, rate=sample_rate))

